
import React from 'react';
import { PredictionResult } from '../types';

interface PredictionCardProps {
  result: PredictionResult | null;
  isPredicting: boolean;
}

const PredictionCard: React.FC<PredictionCardProps> = ({ result, isPredicting }) => {
  const formatLabel = (label: string) => {
    return label.replace("Potato___", "").replace("_", " ");
  };

  return (
    <div className="h-full border-4 border-yellow-400 rounded-2xl bg-white shadow-xl overflow-hidden flex flex-col">
      <div className="bg-yellow-400 px-6 py-3 flex justify-between items-center">
        <h2 className="text-xl font-extrabold text-gray-900 flex items-center gap-2 uppercase tracking-tighter">
          {result ? `Result: ${formatLabel(result.label)}` : 'Prediction'}
        </h2>
        {result && <span className="text-xs bg-black/10 px-2 py-0.5 rounded font-bold">{result.timestamp}</span>}
      </div>

      <div className="flex-grow p-8 flex flex-col justify-center items-center relative min-h-[400px]">
        {!result && !isPredicting && (
          <div className="text-center animate-pulse">
            <div className="w-24 h-24 bg-gray-100 rounded-full flex items-center justify-center mx-auto mb-6 text-gray-300">
              <i className="fas fa-chart-line text-5xl"></i>
            </div>
            <p className="text-gray-400 font-medium">Results will be displayed here after analysis</p>
          </div>
        )}

        {isPredicting && (
          <div className="flex flex-col items-center gap-6">
            <div className="relative">
                <div className="w-20 h-20 border-4 border-yellow-100 border-t-yellow-500 rounded-full animate-spin"></div>
                <div className="absolute inset-0 flex items-center justify-center text-yellow-500">
                    <i className="fas fa-microscope"></i>
                </div>
            </div>
            <p className="text-gray-600 font-bold animate-bounce">Analyzing Neural Patterns...</p>
          </div>
        )}

        {result && !isPredicting && (
          <div className="w-full space-y-10 animate-fade-in-up">
            <div className="flex justify-center">
              <div className={`p-6 rounded-2xl border-2 flex flex-col items-center ${
                result.label.includes('healthy') 
                  ? 'bg-green-50 border-green-200' 
                  : 'bg-red-50 border-red-200'
              }`}>
                <i className={`text-6xl mb-4 ${
                   result.label.includes('healthy') ? 'text-green-500 fas fa-check-circle' : 'text-red-500 fas fa-exclamation-triangle'
                }`}></i>
                <span className="text-3xl font-black text-gray-900 uppercase">{formatLabel(result.label)}</span>
              </div>
            </div>

            <div className="space-y-3">
              <div className="flex justify-between items-end">
                <span className="text-gray-500 font-bold text-sm uppercase tracking-widest">Confidence Level</span>
                <span className="text-2xl font-black text-gray-800">{result.confidence.toFixed(2)}%</span>
              </div>
              
              <div className="h-6 w-full bg-gray-200 rounded-full overflow-hidden p-1 shadow-inner">
                <div 
                  className="h-full bg-gradient-to-r from-gray-500 to-gray-700 rounded-full transition-all duration-1000 ease-out flex items-center justify-end px-3 relative"
                  style={{ width: `${result.confidence}%` }}
                >
                   <div className="absolute inset-0 opacity-20 bg-[url('https://www.transparenttextures.com/patterns/carbon-fibre.png')]"></div>
                </div>
              </div>
              <p className="text-center text-xs text-gray-400 italic">Prediction generated by SVM Layer with MobileNetV2 features</p>
            </div>
          </div>
        )}
      </div>
      
      <div className="p-4 bg-gray-50 border-t text-center">
          <p className="text-[10px] text-gray-400 uppercase tracking-[0.2em] font-bold">Standard Machine Learning Pipeline Verification</p>
      </div>
    </div>
  );
};

export default PredictionCard;
